/**
 * PII classification: decide whether a column holds personal data, what kind,
 * and how sensitive it is — from its name, the same signal `infer.ts` uses to
 * choose a value generator.
 *
 * This is the single source of truth for "is this column PII?". `--scan`
 * privacy reports and private-key handling build on `classifyColumn`.
 * `piiGenerator` additionally supplies realistic fake values for the high-risk
 * categories (SSN, tax id, …) that `infer.ts`'s own name rules don't cover, so
 * anonymization scrubs them to something shaped like the real thing.
 */

import type { Generator } from "./infer.js";
import { ctxFor, has, or, tok, type MatchCtx } from "./match.js";
import type { ColumnInfo, TableInfo } from "./types.js";

export type PiiSensitivity = "high" | "medium" | "low";

export type PiiCategory =
  | "ssn"
  | "tax_id"
  | "passport"
  | "drivers_license"
  | "national_id"
  | "bank_account"
  | "routing_number"
  | "credit_card"
  | "iban"
  | "password"
  | "date_of_birth"
  | "email"
  | "phone"
  | "person_name"
  | "street_address"
  | "ip_address"
  | "geo";

export interface PiiMatch {
  category: PiiCategory;
  sensitivity: PiiSensitivity;
}

interface PiiRule {
  category: PiiCategory;
  sensitivity: PiiSensitivity;
  test: (c: MatchCtx) => boolean;
  /**
   * A fake-value generator. Present only for categories `infer.ts` does not
   * already handle; omitted ones are classified here but generated there.
   */
  gen?: Generator;
}

/**
 * Ordered — first match wins, so specific rules precede generic ones. Rules
 * with no `gen` exist purely so `classifyColumn` reports a complete privacy
 * picture; their values are generated by `infer.ts`'s matching name rules.
 */
const PII_RULES: PiiRule[] = [
  // High-risk government / financial identifiers `infer.ts` does not cover.
  {
    category: "ssn",
    sensitivity: "high",
    test: has("ssn", "socialsecurity"),
    gen: (f) => f.helpers.replaceSymbols("###-##-####"),
  },
  {
    category: "tax_id",
    sensitivity: "high",
    test: or(has("taxid", "vatnumber"), tok("tin", "ein")),
    gen: (f) => f.helpers.replaceSymbols("##-#######"),
  },
  {
    category: "passport",
    sensitivity: "high",
    test: has("passport"),
    gen: (f) => f.string.alphanumeric({ length: 9 }).toUpperCase(),
  },
  {
    category: "drivers_license",
    sensitivity: "high",
    test: has("driverslicense", "driverlicense", "dlnumber", "licensenumber"),
    gen: (f) =>
      f.string.alphanumeric({ length: { min: 8, max: 9 } }).toUpperCase(),
  },
  {
    category: "national_id",
    sensitivity: "high",
    test: has("nationalid", "nationalidentity"),
    gen: (f) => f.string.numeric(10),
  },
  {
    category: "bank_account",
    sensitivity: "high",
    test: has("bankaccount", "accountnumber"),
    gen: (f) => f.finance.accountNumber(),
  },
  {
    category: "routing_number",
    sensitivity: "medium",
    test: or(has("routingnumber"), tok("aba")),
    gen: (f) => f.finance.routingNumber(),
  },

  // Sensitive categories already generated by `infer.ts` — classify only.
  { category: "credit_card", sensitivity: "high", test: has("creditcard", "cardnumber") },
  { category: "iban", sensitivity: "medium", test: tok("iban") },
  { category: "password", sensitivity: "high", test: has("password", "passwd", "pwd") },
  {
    category: "date_of_birth",
    sensitivity: "high",
    test: or(has("birthdate", "dateofbirth", "birthday"), tok("dob")),
  },
  { category: "email", sensitivity: "medium", test: has("email") },
  {
    category: "phone",
    sensitivity: "medium",
    test: or(has("phone", "mobile"), tok("cell", "fax")),
  },
  {
    category: "person_name",
    sensitivity: "medium",
    test: or(
      has("firstname", "givenname", "lastname", "surname", "familyname"),
      has("middlename", "fullname", "displayname"),
    ),
  },
  {
    category: "street_address",
    sensitivity: "medium",
    test: has("addressline", "streetaddress", "street"),
  },
  {
    category: "ip_address",
    sensitivity: "medium",
    test: or(has("ipaddress", "ipaddr"), tok("ip")),
  },
  {
    category: "geo",
    sensitivity: "low",
    test: or(
      has("zipcode", "postalcode", "postcode"),
      tok("city", "town", "country", "zip"),
    ),
  },
];

/** The first PII rule a column name matches, or `null` if it reads as non-PII. */
export function classifyColumn(
  _table: TableInfo,
  col: ColumnInfo,
): PiiMatch | null {
  const ctx = ctxFor(col.name);
  for (const rule of PII_RULES) {
    if (rule.test(ctx)) {
      return { category: rule.category, sensitivity: rule.sensitivity };
    }
  }
  return null;
}

/**
 * A realistic fake generator for a high-risk PII column that `infer.ts` would
 * otherwise miss, or `null`. The caller applies the usual type-compatibility
 * gate before using it.
 */
export function piiGenerator(col: ColumnInfo): Generator | null {
  const ctx = ctxFor(col.name);
  for (const rule of PII_RULES) {
    if (rule.test(ctx)) return rule.gen ?? null;
  }
  return null;
}
